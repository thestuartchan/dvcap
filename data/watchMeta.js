// data/watchMeta.js — a display name and TWO levels of category for the watch universe.
//
// ── WHAT THE BARE TICKER LIST COULD NOT DO ───────────────────────────────────
//
// 1. IT COULD NOT BE READ. The live Asia brief on 2026-09-10 offered "373220.KS +6.46%" as one of
//    five things to look at today. That is LG Energy Solution up six and a half percent, and there
//    is no reading of a Discord message on a phone in which the first form conveys that.
//
// 2. IT COULD NOT SAY WHETHER A MOVE WAS SHARED. lib/watchlist.js compares a mover against its
//    PEERS, and with no category on any entry all sixty-three Asian names landed in one bucket. A
//    bucket that size always contains something up and something down, so every row read "the
//    group is split" — the same five words, on every name, on every run. The corroboration was
//    structurally incapable of saying anything else.
//
// ── WHY TWO LEVELS ───────────────────────────────────────────────────────────
// `cat` is the SECTOR and `sub` is the INDUSTRY, and neither alone works.
//
// Sector alone is too coarse: "tech" is fifty-three of these names, which reproduces the bug one
// level up — TSMC and Adobe are not peers in any sense a day trade cares about.
//
// Industry alone is too fine, and fails in the opposite direction, silently. A name that is the
// only member of its industry in its region has nobody to be corroborated against, and the honest
// output for it is not "moving alone" — that phrase claims its peers went a different way, when in
// fact it has none. Solar is one name. So is gambling.
//
// So the comparison starts at `sub` and WIDENS to `cat` when the sub-group is too thin to carry a
// verdict (lib/watchlist.js owns that threshold and says which level it used). A name with neither
// is compared against nothing at all rather than against everything.
//
// ── SOURCED, NOT ASSUMED ─────────────────────────────────────────────────────
